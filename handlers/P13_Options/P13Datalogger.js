function __updateRomHooks(startAddress){
	 // Get information in ROM provided by datalogger code
	 var DL_VERSION = startAddress + rom.wordAt(startAddress);
	 var STATUS_BYTE_FUNC_LOC = startAddress + rom.wordAt(startAddress + 2);
	 var RX_INT_LOC = startAddress + rom.wordAt(startAddress + 4);
	 var HTS_TABLE_LOC = startAddress + rom.wordAt(startAddress + 6);
	 var QD3_TABLE_LOC = startAddress + rom.wordAt(startAddress + 8);
	
	// Update Vector table for interrupts
	P13.rom_write(0x20 , new Array(
		 RX_INT_LOC & 0xff, RX_INT_LOC >> 8 ) , 0x02);	
	
	// Update status byte function 
	P13.rom_write(0x39B4 , new Array(
		 0x32, STATUS_BYTE_FUNC_LOC & 0xff, STATUS_BYTE_FUNC_LOC >> 8, 0x00 ) , 0x04);
}

function __P13DataloggerMain(startAddress) { 

	// Valid ROM Check
	if(rom.base == 3){
		var addIt = confirm("Would you like to add datalogging code to this ROM?")
		if(addIt){
			__add_P13Datalogger(startAddress);
			alert("QD3 and HTS compatible datalogger has been added. Be sure to update or disable the ROM checksum before using.");
		}

		else{
			return;
		}
	}
	else{
		alert("The open ROM is not compatible with this datalogger." +
			"\nPlease try again with a P11,P12,P13,P14,P39,P51,or P0G ROM"
		);
	}
}
